const LOCALES = { en: 'en-US', uk: 'uk-UA', ru: 'ru-RU' };
let currentLang = 'en';

function t(key, vars) {
  const dict = I18N[currentLang] || I18N.en;
  let s = dict[key];
  if (s === undefined) s = I18N.en[key];
  if (s === undefined) return key;
  if (typeof s === 'object') s = s.other;
  if (vars) Object.keys(vars).forEach((k) => { s = s.split('{' + k + '}').join(vars[k]); });
  return s;
}

function tp(key, n) {
  const dict = I18N[currentLang] || I18N.en;
  const forms = dict[key] || I18N.en[key];
  if (!forms) return String(n);
  const rule = new Intl.PluralRules(LOCALES[currentLang]).select(n);
  const s = forms[rule] || forms.other;
  return s.split('{n}').join(n);
}

function locale() { return LOCALES[currentLang] || 'en-US'; }

function applyI18n(root) {
  const scope = root || document;
  document.documentElement.lang = currentLang;
  scope.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  scope.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  scope.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  scope.querySelectorAll('[data-i18n-alt]').forEach((el) => { el.alt = t(el.dataset.i18nAlt); });
  scope.querySelectorAll('[data-i18n-tip]').forEach((el) => { el.dataset.tip = t(el.dataset.i18nTip); });
  document.querySelectorAll('.lang-switch [data-lang]').forEach((b) => b.classList.toggle('active', b.dataset.lang === currentLang));
}
